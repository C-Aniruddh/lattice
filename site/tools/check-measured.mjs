/**
 * Re-measure every figure `site/data/measured.json` records, and fail when the file disagrees.
 *
 * That file opens by stating its own rule — *"Every number the landing page prints, with the
 * command that produced it... If you cannot name the command, the number does not go on the
 * page"* — and then records the day and commit it was taken on. Both halves were honest. Neither
 * was enforced, and by the next release the file was telling `/llms.txt` there were 2,599 tests
 * (2,648), 524 exported symbols (527), 81.72 kB (83.02) and 32 traps (34). Every one of those had
 * a named command sitting right beside it that nobody re-ran.
 *
 * `build-page.mjs` already did this for one figure: it re-counts `site/example/hello.ts` on every
 * build and refuses to build if `exampleLines` has drifted, with a comment explaining that a number
 * living only in a JSON file drifts from the file it describes the first time somebody edits that
 * file. That reasoning was never specific to the example. This applies it to the rest.
 *
 * Two entry points, because the figures split by what it costs to learn them:
 *
 * - `checkDerivable()` re-derives everything readable from the repository — manifests, source
 *   files, and `npm run size`. `build-page.mjs` calls it, so the site cannot be built with a stale
 *   number in it, including in the Pages workflow where the test suite never runs.
 * - `checkTestCounts()` needs the suite to have actually run, so it reads the counts `npm test`
 *   leaves behind and is called from `npm run verify`, where that always happens. It fails when the
 *   counts file is missing rather than skipping, because a check that quietly does nothing when its
 *   input is absent is the failure this whole file exists to stop.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = dirname(dirname(fileURLToPath(import.meta.url)));
const repo = dirname(site);
const read = (p) => JSON.parse(readFileSync(p, 'utf8'));

/** Where `npm test` leaves the counts. Kept out of git; regenerated by every run. */
export const COUNTS_FILE = join(repo, '.lattice/.test-counts.json');

class Drift extends Error {}

function compare(problems, name, recorded, actual, command) {
  // Numbers are compared as numbers so 83.02 and "83.02" do not read as a disagreement, and the
  // recorded value is printed exactly as it sits in the file so the fix is a copy, not a retype.
  const same = typeof recorded === 'number' ? Math.abs(recorded - actual) < 1e-9 : String(recorded) === String(actual);
  if (!same) {
    problems.push(
      `  ${name}: measured.json says ${JSON.stringify(recorded)}, the repository says ${JSON.stringify(actual)}\n` +
        `      re-measure with: ${command}`,
    );
  }
}

/** Every figure that can be re-derived from the repository as it sits on disk. */
export function checkDerivable() {
  const measured = read(join(site, 'data/measured.json'));
  const kit = read(join(repo, '.lattice/kit.json'));
  const exhibits = read(join(site, 'data/exhibits.json'));
  const fig = (n) => {
    if (measured.figures[n] === undefined) throw new Drift(`measured.json has no figure named ${n}`);
    return measured.figures[n].value;
  };
  const problems = [];

  compare(problems, 'packages', fig('packages'), Object.keys(kit.packages).length, '.lattice/kit.json — packages');

  // The raw sum double-counts: VERSION is exported by eight of the nine, so the page says "unique
  // names" and this has to count them the same way or it will disagree with itself by seventeen.
  const names = new Set();
  for (const pkg of Object.values(kit.packages)) for (const e of pkg.exports ?? []) names.add(e.name ?? e);
  compare(problems, 'publicSymbols', fig('publicSymbols'), names.size, 'unique names across .lattice/kit.json packages.*.exports');

  const traps = (readFileSync(join(repo, 'skills/traps/SKILL.md'), 'utf8').match(/^### /gm) ?? []).length;
  compare(problems, 'traps', fig('traps'), traps, "grep -c '^### ' skills/traps/SKILL.md");

  const skills = execFileSync('find', ['skills', '-name', 'SKILL.md'], { cwd: repo, encoding: 'utf8' })
    .trim()
    .split('\n')
    .filter(Boolean).length;
  compare(problems, 'skills', fig('skills'), skills, 'find skills -name SKILL.md | wc -l');

  compare(problems, 'exhibits', fig('exhibits'), exhibits.live.length, 'site/data/exhibits.json — live[]');
  compare(problems, 'frameBudget', fig('frameBudget'), kit.budgets.maxFrameBudgetMs, '.lattice/kit.json — budgets.maxFrameBudgetMs');
  compare(problems, 'coverageFloor', fig('coverageFloor'), kit.budgets.coverageStatements * 100, '.lattice/kit.json — budgets.coverageStatements');

  // `npm run size` is the command measured.json names for the weights, so it is the command that
  // gets run. Parsing its output rather than reimplementing it is the point: a second implementation
  // could agree with the file while both disagreed with the tool that gates the build.
  const sizeOut = execFileSync('node', ['tools/size.mjs'], { cwd: repo, encoding: 'utf8' });
  const weights = new Map();
  let total = null;
  for (const line of sizeOut.split('\n')) {
    const m = line.match(/^\s{2}(\w+)\s+([\d.]+) kB/);
    if (!m) continue;
    if (m[1] === 'total') total = Number(m[2]);
    else weights.set(m[1], Number(m[2]));
  }
  if (total === null || weights.size === 0) {
    throw new Drift('check-measured: could not read any weight out of `npm run size`. Its output format changed; teach this parser the new one.');
  }
  compare(problems, 'gzipTotal', fig('gzipTotal'), total, 'npm run size — total');
  for (const row of measured.sizes) {
    const actual = weights.get(row.package);
    if (actual === undefined) problems.push(`  sizes[${row.package}]: measured.json lists it, npm run size does not report it`);
    else compare(problems, `sizes[${row.package}].gzipKb`, row.gzipKb, actual, 'npm run size');

    // The budget beside each weight is the gate the package is actually held to, so it comes from
    // kit.json rather than from a second copy. `input`'s override carries several paragraphs of
    // argument for why it is 16; a page still printing 15 quietly reports a package as further
    // inside its budget than the repository agreed it was.
    const budget = kit.budgets.overrides?.[row.package]?.maxGzipKb ?? kit.budgets.maxGzipKbPerPackage;
    compare(problems, `sizes[${row.package}].budgetKb`, row.budgetKb, budget, '.lattice/kit.json — budgets');
  }
  for (const pkg of weights.keys()) {
    if (!measured.sizes.some((r) => r.package === pkg)) problems.push(`  sizes: npm run size reports ${pkg} and measured.json does not list it`);
  }
  return problems;
}

/** The two figures that cost a full test run to learn. */
export function checkTestCounts() {
  if (!existsSync(COUNTS_FILE)) {
    throw new Drift(
      `check-measured: ${COUNTS_FILE} is missing, so the recorded test counts could not be checked.\n` +
        '  `npm test` writes it. Run the suite, then this check — skipping it is how the number went stale.',
    );
  }
  const measured = read(join(site, 'data/measured.json'));
  const counts = read(COUNTS_FILE);
  const problems = [];
  compare(problems, 'tests', measured.figures.tests.value, counts.numTotalTests, 'npm test');
  compare(problems, 'testFiles', measured.figures.testFiles.value, counts.testResults.length, 'npm test');
  return problems;
}

const isMain = process.argv[1] && import.meta.url === `file://${process.argv[1]}`;
if (isMain) {
  try {
    const problems = [...checkDerivable(), ...checkTestCounts()];
    if (problems.length > 0) {
      console.error(
        `\nsite/data/measured.json has drifted from the repository in ${problems.length} place${problems.length === 1 ? '' : 's'}.\n` +
          'Every figure below is printed on the landing page or served from /llms.txt and /api.json,\n' +
          'where an agent reads it as fact. Update the file to the measured column.\n\n' +
          problems.join('\n') +
          '\n\nAlso update measured.json\'s `commit` and `measuredOn`, which claim when this was last true.\n',
      );
      process.exit(1);
    }
    console.log('measured.json agrees with the repository');
  } catch (err) {
    console.error(err instanceof Drift ? `\n${err.message}\n` : err);
    process.exit(1);
  }
}
